"""Note session submission and note generation route handlers.

All endpoints are authenticated — note sessions are user-scoped data.
The current user is resolved from the session token at the router
level and passed explicitly to service functions.
"""

from __future__ import annotations

import json
import logging
import uuid
from typing import AsyncGenerator, Optional

from fastapi import APIRouter, Depends, HTTPException, Request
from fastapi.responses import StreamingResponse
from pydantic import BaseModel, Field
from sqlalchemy import select
from sqlalchemy.ext.asyncio import AsyncSession

from app.core.auth import get_current_user
from app.core.db import AsyncSessionLocal, get_async_session
from app.models.coverage_event import CoverageEvent, EventType
from app.models.note_session import NoteSource
from app.models.section import Section
from app.pipeline.note_gen import generate_section_notes
from app.services.notes import (
    NoteBatchNote,
    NoteBlockDraft,
    NoteDetailResponse,
    NoteSessionListResponse,
    NoteSessionResponse,
    create_note_session,
    create_note_with_blocks,
    get_note_detail,
    list_note_sessions,
    list_notes_for_section,
    replace_note_blocks,
    upsert_notes_batch,
)
from app.services.note_topic import stream_topic_note

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/notes", tags=["notes"])


# ── Request schemas ────────────────────────────────────────────


class CreateNoteSessionRequest(BaseModel):
    """Request body for ``POST /notes``."""

    book_id: uuid.UUID
    raw_text: str
    source: NoteSource
    title: Optional[str] = None


class GenerateNotesRequest(BaseModel):
    """Request body for ``POST /notes/generate``."""

    book_id: uuid.UUID
    chapter_start: int = 0
    chapter_end: int = 0


class CreateNoteDocumentRequest(BaseModel):
    """Request body for ``POST /notes/document``.

    ``blocks`` may be empty: the editor creates a blank note so the caret is
    live before the first keystroke. ``source`` defaults to ``pasted`` because
    a note the student writes is not model output; topic generation passes
    ``ai_generated`` instead.
    """

    book_id: uuid.UUID
    blocks: list[NoteBlockDraft] = []
    title: Optional[str] = None
    source: NoteSource = NoteSource.PASTED


class ReplaceBlocksRequest(BaseModel):
    """Request body for ``PUT /notes/{note_id}/blocks``.

    The whole ordered list is sent: an autosave is a save of what the editor
    holds, not a patch. Blocks that already exist carry their ``id`` so their
    links survive the save.
    """

    blocks: list[NoteBlockDraft]


# ── Endpoints ──────────────────────────────────────────────────


@router.get("", response_model=NoteSessionListResponse)
async def get_note_sessions(
    book_id: uuid.UUID,
    section_id: Optional[uuid.UUID] = None,
    limit: int = 50,
    offset: int = 0,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> NoteSessionListResponse:
    """List note sessions for a user + book, most recent first.

    With ``section_id`` the list narrows to notes that cite that section, which
    is what the reader shows while the student is on it. Same response shape, so
    the client keeps one type.
    """
    if section_id is not None:
        return await list_notes_for_section(
            db,
            user_id=user_id,
            book_id=book_id,
            section_id=section_id,
            limit=limit,
        )

    return await list_note_sessions(
        db,
        user_id=user_id,
        book_id=book_id,
        limit=limit,
        offset=offset,
    )


@router.post("", response_model=NoteSessionResponse, status_code=201)
async def post_note_session(
    body: CreateNoteSessionRequest,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> NoteSessionResponse:
    """Submit a note session for similarity matching.

    Creates a ``NoteSession`` record and enqueues a background Dramatiq
    job to run the similarity pass. Returns immediately with the session
    ID and job ID for status polling.

    The ``source`` field specifies whether the notes were pasted by the
    user (``pasted``) or generated by AI (``ai_generated``).
    """
    return await create_note_session(
        db,
        user_id=user_id,
        book_id=body.book_id,
        raw_text=body.raw_text,
        source=body.source,
        title=body.title,
    )


@router.post("/generate")
async def post_generate_notes(
    body: GenerateNotesRequest,
    user_id: uuid.UUID = Depends(get_current_user),
) -> StreamingResponse:
    """Generate AI study notes for a chapter range, streamed section by section.

    Accepts a book ID and chapter range. For each section in the range,
    the LLM (Cerebras) generates structured notes grounded exclusively
    in that section's text and metadata. Results are streamed as
    newline-delimited JSON (NDJSON) — one ``GeneratedSectionNotes``
    object per line.

    After each section completes, a ``notes_generated`` coverage event
    is emitted so the coverage map reflects the new contribution.
    """
    return StreamingResponse(
        _generate_notes_stream(user_id, body.book_id, body.chapter_start, body.chapter_end),
        media_type="application/x-ndjson",
        headers={
            "X-Accel-Buffering": "no",  # disable nginx buffering
            "Cache-Control": "no-cache",
        },
    )


# ── Note documents ─────────────────────────────────────────────


@router.post("/document", response_model=NoteDetailResponse, status_code=201)
async def post_note_document(
    body: CreateNoteDocumentRequest,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> NoteDetailResponse:
    """Create a note document from blocks (possibly none at all).

    No similarity job is queued: a block note's links come from generation or
    from the student, so the section-level matcher has nothing to add.
    """
    return await create_note_with_blocks(
        db,
        user_id=user_id,
        book_id=body.book_id,
        blocks=body.blocks,
        source=body.source,
        title=body.title,
    )


class UpsertNotesBatchRequest(BaseModel):
    """Request body for ``POST /notes/batch`` -- the write-behind flush."""

    notes: list[NoteBatchNote] = []
    deleted: list[uuid.UUID] = []


@router.post("/batch")
async def post_notes_batch(
    body: UpsertNotesBatchRequest,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> dict:
    """Upsert many notes' current state in one transaction (local-first sync).

    The client flushes its dirty notes here on a debounce; each note carries its
    full block list and client ids, so the write is idempotent and one request
    replaces N per-note saves.
    """
    synced = await upsert_notes_batch(
        db, user_id=user_id, notes=body.notes, deleted=body.deleted
    )
    return {
        "synced": [
            {"id": str(note_id), "updated_at": ts.isoformat()}
            for note_id, ts in synced
        ]
    }


@router.get("/{note_id}", response_model=NoteDetailResponse)
async def get_note(
    note_id: uuid.UUID,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> NoteDetailResponse:
    """Read one note with its blocks and links.

    A note belonging to someone else is reported as missing rather than
    forbidden: the caller has no business knowing it exists.
    """
    note = await get_note_detail(db, user_id=user_id, note_id=note_id)
    if note is None:
        raise HTTPException(status_code=404, detail="Note not found")
    return note


@router.put("/{note_id}/blocks", response_model=NoteDetailResponse)
async def put_note_blocks(
    note_id: uuid.UUID,
    body: ReplaceBlocksRequest,
    user_id: uuid.UUID = Depends(get_current_user),
    db: AsyncSession = Depends(get_async_session),
) -> NoteDetailResponse:
    """Autosave the editor's whole block list.

    Blocks are diffed by id, so a block that survives the save keeps its links.
    The saved document comes back so the client can pick up ids for blocks it
    has just created.
    """
    try:
        return await replace_note_blocks(
            db, user_id=user_id, note_id=note_id, blocks=body.blocks,
        )
    except ValueError as exc:
        raise HTTPException(status_code=404, detail="Note not found") from exc


# ── Topic notes ────────────────────────────────────────────────

class GenerateTopicRequest(BaseModel):
    """Request body for ``POST /notes/topic``."""

    book_id: uuid.UUID
    topic: str = Field(min_length=1, max_length=200)


@router.post("/topic")
async def post_topic_note(
    body: GenerateTopicRequest,
    user_id: uuid.UUID = Depends(get_current_user),
) -> StreamingResponse:
    """Generate notes from a topic, streamed as NDJSON events."""
    return StreamingResponse(
        _topic_events(user_id, body.book_id, body.topic),
        media_type="application/x-ndjson",
        headers={
            "X-Accel-Buffering": "no",
            "Cache-Control": "no-cache",
        },
    )


async def _topic_events(
    user_id: uuid.UUID,
    book_id: uuid.UUID,
    topic: str,
) -> AsyncGenerator[bytes, None]:
    """Relay the service's events as NDJSON.

    The generator opens its own session, as the chapter-range stream does: a
    request-scoped one is closed before a long stream finishes.
    """
    async with AsyncSessionLocal() as db:
        async for event in stream_topic_note(
            db, user_id=user_id, book_id=book_id, topic=topic
        ):
            yield (json.dumps(event) + "\n").encode()


# ── Streaming generator ────────────────────────────────────────


async def _generate_notes_stream(
    user_id: uuid.UUID,
    book_id: uuid.UUID,
    chapter_start: int,
    chapter_end: int,
) -> AsyncGenerator[bytes, None]:
    """Async generator that yields NDJSON lines of generated notes."""
    async with AsyncSessionLocal() as db:
        try:
            # Fetch sections in the chapter range, ordered by hierarchy
            result = await db.execute(
                select(Section)
                .where(
                    Section.book_id == book_id,
                    Section.chapter_index >= chapter_start,
                    Section.chapter_index <= chapter_end,
                )
                .order_by(Section.chapter_index, Section.section_index)
            )
            sections = result.scalars().all()

            if not sections:
                yield json.dumps({"error": "No sections found in this chapter range"}).encode() + b"\n"
                return

            for section in sections:
                # Skip connective sections — too short for meaningful notes
                if section.is_connective:
                    continue

                # Skip sections without raw text
                if not section.raw_text:
                    continue

                try:
                    notes = await generate_section_notes(
                        section_id=str(section.id),
                        heading=section.heading,
                        raw_text=section.raw_text,
                        page_start=section.page_start,
                        page_end=section.page_end,
                        metadata=section.section_metadata,
                    )

                    # Emit coverage event for this section
                    db.add(
                        CoverageEvent(
                            user_id=user_id,
                            book_id=book_id,
                            section_id=section.id,
                            event_type=EventType.NOTES_GENERATED,
                            event_metadata={
                                "chapter_range": f"{chapter_start}-{chapter_end}",
                            },
                        )
                    )
                    await db.flush()

                    # Yield the generated notes as NDJSON
                    yield notes.model_dump_json().encode() + b"\n"

                except Exception as e:
                    logger.warning(
                        "Note generation failed for section %s: %s",
                        section.id, e,
                    )
                    # Yield a minimal error placeholder so the stream continues
                    error_line = json.dumps({
                        "section_id": str(section.id),
                        "section_heading": section.heading,
                        "error": str(e),
                    })
                    yield error_line.encode() + b"\n"

            await db.commit()

        except Exception:
            await db.rollback()
            raise
