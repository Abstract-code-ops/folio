"""Q&A streaming endpoint route handlers.

All endpoints are authenticated — Q&A messages are user-scoped data.
The current user is resolved from the session token at the router
level.

Q&A is **book-scoped**: the question is answered using content from
all sections of the specified book. The top-k most relevant chunks
across all sections are retrieved to ground the answer.
"""

from __future__ import annotations

import json
import logging
import uuid
from typing import AsyncGenerator

from fastapi import APIRouter, Depends
from fastapi.responses import StreamingResponse
from pydantic import BaseModel

from app.core.auth import get_current_user
from app.core.db import AsyncSessionLocal
from app.models.coverage_event import CoverageEvent, EventType
from app.models.qa_message import QAMessage
from app.pipeline.qa_chain import answer_question_stream, build_context, summarize_conversation
from app.services.qa import build_citations, retrieve_top_chunks

logger = logging.getLogger(__name__)

router = APIRouter(prefix="/qa", tags=["qa"])



# ── Request schemas ────────────────────────────────────────────


class AskQuestionRequest(BaseModel):
    """Request body for ``POST /qa/{book_id}``."""

    question: str
    summary: str | None = None
    history: list[dict[str, str]] = []


class SummarizeRequest(BaseModel):
    """Request body for ``POST /qa/summarize``."""

    messages: list[dict[str, str]]


# ── Endpoints ──────────────────────────────────────────────────


@router.post("/summarize")
async def summarize(body: SummarizeRequest) -> dict[str, str]:
    """Summarize a chat transcript into a short running summary via VoidAI."""
    if not body.messages:
        return {"summary": ""}
    summary = await summarize_conversation(body.messages)
    return {"summary": summary}


@router.post("/{book_id}")
async def ask_question(
    book_id: uuid.UUID,
    body: AskQuestionRequest,
    user_id: uuid.UUID = Depends(get_current_user),
) -> StreamingResponse:
    """Ask a question about the book, stream a grounded answer.

    The question is answered using content from all sections of the
    specified book. The top-k most relevant chunks are retrieved via
    embedding similarity, and the answer is generated by Cerebras
    grounded exclusively in those chunks.

    The response is streamed as NDJSON with event types:
    - ``token`` — answer text fragments
    - ``citation`` — source citation objects (with section heading,
      page range, excerpt)
    - ``done`` — end of stream marker with ``qa_message_id``
    """
    return StreamingResponse(
        _qa_stream(user_id, book_id, body.question, body.summary, body.history),
        media_type="application/x-ndjson",
        headers={
            "X-Accel-Buffering": "no",
            "Cache-Control": "no-cache",
        },
    )


# ── Streaming generator ────────────────────────────────────────


async def _qa_stream(
    user_id: uuid.UUID,
    book_id: uuid.UUID,
    question: str,
    summary: str | None = None,
    history: list[dict[str, str]] | None = None,
) -> AsyncGenerator[bytes, None]:
    """Async generator: retrieve chunks via pgvector → stream answer → persist."""
    full_answer: str = ""
    source_citations: list[dict] = []

    async with AsyncSessionLocal() as db:
        try:
            # 1. Retrieve top-k chunks via pgvector cosine distance
            top_chunks = await retrieve_top_chunks(db, book_id, question)

            if not top_chunks:
                yield json.dumps({
                    "type": "not_covered",
                    "text": "This book has no indexed content for Q&A.",
                }).encode() + b"\n"
                return

            # 2. Build grounding context from the retrieved chunks
            context = build_context([(chunk, 0.0) for chunk in top_chunks])

            # 3. Build citation events (emitted after the answer streams)
            citations = build_citations(top_chunks)
            source_citations = list(citations)

            # 4. Stream the grounded answer as token events first
            async for event_bytes in answer_question_stream(
                question=question,
                context=context,
                summary=summary,
                history=history,
            ):
                event = json.loads(event_bytes)
                if event.get("type") == "token":
                    full_answer += event.get("text", "")
                yield event_bytes

            # 5. Emit citation events after the answer has streamed
            for citation in citations:
                yield json.dumps(citation).encode() + b"\n"

            # 6. Persist the Q&A message
            top_section_id = top_chunks[0].section_id

            qa_message = QAMessage(
                user_id=user_id,
                book_id=book_id,
                section_id=top_section_id,
                question=question,
                answer=full_answer,
                sources=source_citations if source_citations else None,
            )
            db.add(qa_message)

            # 6. Emit coverage events — one per contributing section
            contributing_section_ids: set[uuid.UUID] = {
                c.section_id for c in top_chunks
            }
            for sid in contributing_section_ids:
                db.add(
                    CoverageEvent(
                        user_id=user_id,
                        book_id=book_id,
                        section_id=sid,
                        event_type=EventType.QA_ASKED,
                        event_metadata={
                            "qa_message_id": str(qa_message.id),
                        },
                    )
                )

            await db.commit()

            # Yield a final done event with the message ID
            yield json.dumps({
                "type": "done",
                "qa_message_id": str(qa_message.id),
            }).encode() + b"\n"

        except Exception as e:
            await db.rollback()
            logger.exception("Q&A stream failed for book %s", book_id)
            yield json.dumps({
                "type": "error",
                "text": f"An error occurred: {str(e)}",
            }).encode() + b"\n"